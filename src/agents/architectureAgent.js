/**
 * ArchitectureAgent
 * Proposes a high-level system architecture based on the parsed constraints.
 */

const { addHistory } = require("./state");

function runArchitectureAgent(project) {
  const c = project.user_intent.parsed_constraints;

  // Very simple decision logic for the first version.
  // Later this will be driven by an LLM + knowledge base.

  let mcu = c.mcu_preference || "esp32";
  let wireless = c.wireless || "ble";
  let power = c.power || "battery";
  let form = c.form_factor || "module";

  // Reasonable defaults based on common patterns
  if (wireless === "ble" && !c.mcu_preference) {
    mcu = "esp32"; // or nrf52 – we keep esp32 as safe default for now
  }
  if (wireless === "wifi" && !c.mcu_preference) {
    mcu = "esp32";
  }
  if (wireless === "lora" && !c.mcu_preference) {
    mcu = "esp32"; // many LoRa boards are ESP32-based
  }

  const blocks = [
    { name: "MCU", part_family: mcu, notes: "Main application processor" }
  ];

  if (wireless) {
    blocks.push({
      name: "Wireless", 
      part_family: wireless === "ble" ? "BLE (integrated or module)" : wireless,
      notes: `Connectivity: ${wireless}`
    });
  }

  if (power === "battery") {
    blocks.push({
      name: "Power", 
      part_family: "Battery management + regulator",
      notes: "LiPo or coin-cell friendly power path"
    });
  } else {
    blocks.push({
      name: "Power",
      part_family: "USB / external supply + regulator",
      notes: "Non-battery powered"
    });
  }

  // Add sensor blocks
  (c.sensors || []).forEach(sensor => {
    blocks.push({
      name: `Sensor: ${sensor}`,
      part_family: sensor,
      notes: `Required by user`
    });
  });

  // Simple estimated BOM cost range
  let estimatedBomLow = 4;
  let estimatedBomHigh = 12;

  if (c.sensors && c.sensors.length > 2) {
    estimatedBomLow += 3;
    estimatedBomHigh += 8;
  }
  if (wireless === "cellular") {
    estimatedBomLow += 8;
    estimatedBomHigh += 20;
  }
  if (c.target_cost && c.target_cost < estimatedBomLow) {
    // flag that target may be aggressive
  }

  const architecture = {
    mcu_family: mcu,
    wireless,
    power_architecture: power,
    form_factor: form,
    blocks,
    estimated_bom_usd: {
      low: estimatedBomLow,
      high: estimatedBomHigh
    },
    notes: [
      "This is a first-pass architecture generated by rules.",
      "A real LLM + component knowledge base will replace this logic later."
    ],
    confidence: 0.68
  };

  project.architecture = architecture;

  addHistory(project, "ArchitectureAgent", "proposed_architecture", {
    mcu,
    wireless,
    block_count: blocks.length
  });

  return {
    project,
    confidence: architecture.confidence,
    risk_level: "medium",
    summary: `Proposed ${mcu}-based architecture with ${blocks.length} major blocks.`
  };
}

module.exports = { runArchitectureAgent };
